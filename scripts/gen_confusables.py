"""Generate GuardBit's single-letter Latin subset of Unicode confusables."""

import re
import string
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/raw/confusables.txt"
OUTPUT = ROOT / "backend/app/detect/confusables_map.py"


def generate(source: Path = SOURCE, output: Path = OUTPUT) -> int:
    text = source.read_text(encoding="utf-8-sig")
    version = re.search(r"^#\s*Version:\s*(\S+)", text, re.MULTILINE)
    date = re.search(r"^#\s*Date:\s*(.+?)\s*$", text, re.MULTILINE)
    mapping = {}
    for line in text.splitlines():
        fields = line.split("#", 1)[0].split(";")
        if len(fields) < 2:
            continue
        source_points, target_points = fields[0].split(), fields[1].split()
        if len(source_points) != 1 or len(target_points) != 1:
            continue
        char, target = chr(int(source_points[0], 16)), chr(int(target_points[0], 16))
        # ASCII sources stay untouched; leetspeak digits are handled by context rules.
        if ord(char) > 127 and target in string.ascii_letters:
            mapping[char] = target
    lines = [
        "# Generated by scripts/gen_confusables.py; do not edit by hand.",
        "# Source: Unicode confusables.txt for Unicode Security Mechanisms (UTS #39).",
        f"# Version: {version.group(1) if version else 'unknown'}",
        f"# Source date: {date.group(1) if date else 'unknown'}",
        "# Data copyright Unicode, Inc.; use under the Unicode License / Terms of Use:",
        "# https://www.unicode.org/license.txt and https://www.unicode.org/terms_of_use.html",
        "# Subset: one non-ASCII source character to one ASCII letter A-Z or a-z.",
        "# Regenerate from repo root: python scripts/gen_confusables.py",
        "",
        "CONFUSABLES = {",
        *(f"    {ascii(char)}: {target!r},  # U+{ord(char):04X}" for char, target in sorted(mapping.items())),
        "}",
        "",
    ]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return len(mapping)


if __name__ == "__main__":
    count = generate(*(Path(arg) for arg in sys.argv[1:3]))
    print(f"{count} entries")
